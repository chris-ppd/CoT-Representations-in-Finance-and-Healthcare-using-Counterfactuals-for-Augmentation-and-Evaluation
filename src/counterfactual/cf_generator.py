def _load_qwen(
    model_name: str, quantization: str | None, model_suff: str | None = None
):
    global _qwen_model, _qwen_tokenizer
    if _qwen_model is None:
        if model_suff:
            model_name = f"{model_name}-{model_suff}"
        logger.info(f"Loading Qwen: {model_name}")
        quant_cfg = (
            BitsAndBytesConfig(load_in_8bit=True) if quantization == "8bit" else None
        )
        _qwen_tokenizer = AutoTokenizer.from_pretrained(model_name)
        _qwen_tokenizer.padding_side = "left"
        if _qwen_tokenizer.pad_token is None:
            _qwen_tokenizer.pad_token = _qwen_tokenizer.eos_token
        _qwen_model = AutoModelForCausalLM.from_pretrained(
            model_name,
            quantization_config=quant_cfg,
            torch_dtype=torch.float16,
            device_map="auto",
        )
        print_memory_usage("after Qwen load")
    return _qwen_model, _qwen_tokenizer


def _load_validator(model_path: str):
    global _validator_pipes
    resolved = str(resolve_path(model_path))
    if resolved not in _validator_pipes:
        logger.info(f"Loading flip-gate validator: {resolved}")
        tokenizer = AutoTokenizer.from_pretrained(resolved)
        tokenizer.truncation_side = "left"
        _validator_pipes[resolved] = pipeline(
            "text-classification",
            model=resolved,
            tokenizer=tokenizer,
            top_k=None,
            device="cpu",
        )
    return _validator_pipes[resolved]


