"""
Counterfactual generation pipeline — Script 2 of 2.

Mirrors the ER-REASON preprocessing pipeline structure exactly.  Per batch of
batch_size profiles Qwen is called exactly 9 times: once per sentence slot
(8 total: 4 steps × 2 sentences) plus once for the answer rewrite.  Each call
processes the full batch of N profiles in a single model.generate() call.

For each slot, every profile in the batch receives exactly one prompt:
  - profiles with LIME features in that slot → rewrite instruction
  - profiles without LIME features in that slot → "Return exactly the word: None"
Responses of "None" (case-insensitive) are discarded; others stored as the
rewritten sentence for that slot.  The answer rewrite call follows the same
pattern.

Four models are loaded once at startup and reused across all batches:

  Qwen3-4B (8-bit, GPU)      — sentence rewriting and answer generation
  FinBERT/MedBERT (CPU)       — hard label flip gate
  all-mpnet-base-v2 (CPU)     — cosine similarity (proximity)
  GPT-2 117M (CPU)            — perplexity (fluency, independent of Qwen)

Retry structure: all batches run first, collecting failures into a global
list.  After all batches complete, up to max_retries global retry rounds
process all failed profiles together in batches of batch_size.

Output schema per record:
  id, original_id, original_cot_text, original_answer_text,
  counterfactual_cot_text, counterfactual_answer_text,
  original_label, counterfactual_label, modified_sentences,
  top_k_words, cosine_similarity, ppl, retries
"""

