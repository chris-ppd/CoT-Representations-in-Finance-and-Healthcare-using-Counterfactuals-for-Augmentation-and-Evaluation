def _check_label_flip_batch(
    cf_texts: list[str],
    original_labels: list[int],
    validator_pipe,
    label_map: dict[str, int],
) -> list[tuple[bool, int, float]]:
    """Return (flipped, predicted_label_int, confidence) per pair."""
    all_scores = validator_pipe(
        cf_texts, truncation=True, max_length=512, batch_size=32
    )
    results = []
    for scores, original_label in zip(all_scores, original_labels):
        best = max(scores, key=lambda x: x["score"])
        pred = label_map.get(best["label"], -1)
        target_int = 1 - original_label
        results.append((pred == target_int, pred, best["score"]))
    return results


