def _load_prompt(dataset_name: str, prompt_type: str) -> str:
    """Load a CF system prompt file for the given dataset and prompt type.

    Args:
        dataset_name: Sub-dataset key (e.g. "ld1", "er-reason").
        prompt_type:  "sentence" or "answer".

    Raises:
        FileNotFoundError: If the expected prompt file does not exist.
    """
    path = (
        PROJECT_ROOT
        / "prompts"
        / "cf"
        / f"{dataset_name}_cf_{prompt_type}_system_prompt.txt"
    )
    if not path.exists():
        raise FileNotFoundError(
            f"System prompt file not found for dataset '{dataset_name}' ({prompt_type}).\n"
            f"Expected: {path}\n"
            f"Create the file at: prompts/cf/{dataset_name}_cf_{prompt_type}_system_prompt.txt"
        )
    return path.read_text(encoding="utf-8").strip()


def _load_processed_original_ids(output_path: Path) -> set:
    """Read original_id values from output JSONL to support resumption."""
    processed: set = set()
    if output_path.exists():
        with open(output_path, "r") as f:
            for line in f:
                processed.add(json.loads(line.strip())["original_id"])
    return processed


