def _reconstruct_cot_steps(
    cot_text_only: str,
    modified_sentences: dict[tuple[int, int], str],
) -> str:
    """Rebuild CoT steps by substituting rewritten sentences at their slot positions.

    Uses clean [ES] / [EORS] split-join — no regex, no char offsets.
    [STEP] is stripped at the step level before sentence substitution and
    re-prepended so that clean modified sentences never carry the marker.
    """
    steps = cot_text_only.split("[EORS]")
    for step_idx, step in enumerate(steps):
        has_step_token = "[STEP]" in step
        step_body = step.replace("[STEP]", "") if has_step_token else step
        sentences = step_body.split("[ES]")
        for sent_idx in range(len(sentences)):
            if (step_idx, sent_idx) in modified_sentences:
                sentences[sent_idx] = modified_sentences[(step_idx, sent_idx)]
        body = "[ES]".join(sentences)
        steps[step_idx] = ("[STEP]" + body) if has_step_token else body
    return "[EORS]".join(steps)


def _normalize_cot_spacing(text: str) -> str:
    """Normalize whitespace around CoT special tokens after reconstruction.

    Applies after _reconstruct_cot_steps so that spacing is consistent
    regardless of what Qwen returns for any individual sentence.
    """
    text = re.sub(r"\s*\[STEP\]\s*", "\n[STEP] ", text)
    text = re.sub(r"\s*\[ES\]\s*", " [ES] ", text)
    text = re.sub(r"\s*\[EORS\]\s*", " [EORS]\n", text)
    text = re.sub(r"\s*\[ANSWER\]\s*", "\n[ANSWER] ", text)
    text = re.sub(r"\s*\[EOA\]", " [EOA]", text)
    return text.strip()


def _check_token_budget(text: str, max_tokens: int = 512) -> bool:
    """Return True if text fits within max_tokens under the BERT tokenizer."""
    tok = _get_bert_tokenizer()
    count = len(tok(text, truncation=False, add_special_tokens=True)["input_ids"])
    return count <= max_tokens


