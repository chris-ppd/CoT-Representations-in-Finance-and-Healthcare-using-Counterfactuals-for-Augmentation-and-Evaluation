# CF hidden-state extraction (single forward pass per approved profile)
# ---------------------------------------------------------------------------


def _extract_cf_profile_hidden_states(
    original_id: str,
    cot_text: str,
    answer_text: str,
    model: AutoModelForCausalLM,
    tokenizer: AutoTokenizer,
    eors_sequences: tuple,
    eoa_sequences: tuple,
    hidden_dim: int,
    temp_dir: Path,
) -> tuple:
    """Forward-pass hidden state extraction for one approved CF profile.

    Accepts the cot steps and answer parts already split so that each half is
    encoded separately — avoiding BPE merge artifacts at the boundary between
    the two model.generate() calls that produced them.  Runs one forward pass
    with output_hidden_states=True and slices the last hidden layer at the 4
    [EORS] and 1 [EOA] positions found by _find_extraction_positions.

    On success: saves to temp_dir via save_hidden_states_temp and returns
        (cot_states, answer_state, eors_positions, eoa_position, None).
    On failure: returns (None, None, None, None, error_message) — caller logs
        and skips; no temp files are written.
    """
    # Encode cot steps and answer block separately — the two halves were
    # generated by different model.generate() calls so re-tokenising them
    # together can produce different BPE boundaries at the junction.
    ids = tokenizer.encode(cot_text, add_special_tokens=False) + tokenizer.encode(
        answer_text, add_special_tokens=False
    )

    if not ids:
        return None, None, None, None, f"Profile {original_id}: empty token sequence."

    input_tensor = torch.tensor([ids], dtype=torch.long).to(model.device)
    with torch.no_grad():
        outputs = model(input_ids=input_tensor, output_hidden_states=True)

    # Last hidden layer: (1, seq_len, hidden_dim) → (seq_len, hidden_dim) float32
    hidden_states = outputs.hidden_states[-1].squeeze(0).float()
    del outputs, input_tensor
    torch.cuda.empty_cache()

    eors_positions, eoa_positions = _find_extraction_positions(
        ids, eors_sequences, eoa_sequences
    )

    if len(eors_positions) != 4:
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: expected 4 [EORS] tokens, found {len(eors_positions)}.",
        )
    if len(eoa_positions) != 1:
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: expected 1 [EOA] token, found {len(eoa_positions)}.",
        )

    eoa_position = eoa_positions[0]
    if eoa_position <= eors_positions[-1]:
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: [EOA] position {eoa_position} does not follow "
            f"last [EORS] position {eors_positions[-1]}.",
        )

    try:
        cot_states = torch.stack(
            [hidden_states[pos] for pos in eors_positions]
        )  # (4, hidden_dim)
    except IndexError as exc:
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: index error at [EORS] — {exc}.",
        )

    try:
        answer_state = hidden_states[eoa_position]  # (hidden_dim,)
    except IndexError as exc:
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: index error at [EOA] — {exc}.",
        )

    if cot_states.shape != (4, hidden_dim):
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: unexpected CoT states shape {tuple(cot_states.shape)}, "
            f"expected (4, {hidden_dim}).",
        )
    if answer_state.shape != (hidden_dim,):
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: unexpected answer state shape {tuple(answer_state.shape)}, "
            f"expected ({hidden_dim},).",
        )

    all_states = torch.cat(
        [cot_states, answer_state.unsqueeze(0)], dim=0
    )  # (5, hidden_dim)
    norms = all_states.norm(dim=-1)
    if (norms == 0).any():
        bad = norms.eq(0).nonzero(as_tuple=True)[0].tolist()
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: zero-norm hidden state(s) at extraction point(s) {bad}.",
        )

    dists = F.pdist(all_states, p=2)
    if (dists < 1e-6).any():
        return (
            None,
            None,
            None,
            None,
            f"Profile {original_id}: duplicate hidden state vectors detected (pairwise L2 < 1e-6).",
        )

    save_hidden_states_temp(
        original_id, cot_states, answer_state, eors_positions, eoa_position, temp_dir
    )
    return cot_states, answer_state, eors_positions, eoa_position, None


