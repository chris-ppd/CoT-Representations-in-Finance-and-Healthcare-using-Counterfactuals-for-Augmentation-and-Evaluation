def _filter_positive_features(features: list[dict], top_k: int) -> list[dict]:
    """Return up to top_k features with positive LIME score, ranked descending."""
    positive = [f for f in features if f["score"] > 0]
    positive.sort(key=lambda x: x["score"], reverse=True)
    return positive[:top_k]


