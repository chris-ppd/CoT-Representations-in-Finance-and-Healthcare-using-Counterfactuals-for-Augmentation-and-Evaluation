def _compute_cosine_similarities(
    originals: list[str],
    counterfactuals: list[str],
    sbert: SentenceTransformer,
) -> list[float]:
    """Encode originals and CFs together, return per-pair cosine similarity."""
    all_texts = originals + counterfactuals
    embs = sbert.encode(all_texts, show_progress_bar=False, convert_to_numpy=True)
    n = len(originals)
    orig_embs = embs[:n]
    cf_embs = embs[n:]
    norms_o = np.linalg.norm(orig_embs, axis=1, keepdims=True)
    norms_c = np.linalg.norm(cf_embs, axis=1, keepdims=True)
    dots = np.sum(orig_embs * cf_embs, axis=1)
    sims = dots / (norms_o.squeeze() * norms_c.squeeze() + 1e-8)
    return sims.tolist()


def _compute_perplexity(
    texts: list[str],
    gpt2: GPT2LMHeadModel,
    gpt2_tok: GPT2TokenizerFast,
) -> list[float]:
    """Batch-compute per-sequence perplexity using GPT-2 (CPU).

    GPT-2 is used because it is independent of Qwen3-4B — scoring with any
    Qwen variant would be circular since Qwen generated the text.
    """
    enc = gpt2_tok(
        texts,
        return_tensors="pt",
        padding=True,
        truncation=True,
        max_length=1024,
    )
    input_ids = enc["input_ids"]
    attention_mask = enc["attention_mask"]
    labels = input_ids.clone()
    labels[attention_mask == 0] = -100

    with torch.no_grad():
        outputs = gpt2(input_ids=input_ids, attention_mask=attention_mask)

    logits = outputs.logits
    shift_logits = logits[:, :-1, :].contiguous()
    shift_labels = labels[:, 1:].contiguous()

    loss_fn = torch.nn.CrossEntropyLoss(reduction="none", ignore_index=-100)
    per_token_loss = loss_fn(
        shift_logits.view(-1, shift_logits.size(-1)),
        shift_labels.view(-1),
    ).view(len(texts), -1)

    valid_mask = (shift_labels != -100).float()
    valid_counts = valid_mask.sum(dim=-1).clamp(min=1)
    per_seq_loss = (per_token_loss * valid_mask).sum(dim=-1) / valid_counts
    return torch.exp(per_seq_loss).tolist()


