def _process_batch(
    batch: list[dict],
    f_out,
    qwen: AutoModelForCausalLM,
    qwen_tok: AutoTokenizer,
    validator_pipe,
    sbert: SentenceTransformer,
    gpt2: GPT2LMHeadModel,
    gpt2_tok: GPT2TokenizerFast,
    id2label: dict[int, str],
    validator_config: ValidatorConfig,
    lime_features: dict,
    top_k: int,
    max_new_tokens: int,
    sentence_system_prompt: str,
    answer_system_prompt: str,
    sub_dataset: str,
    on_approved=None,
) -> tuple[list[dict], int, list[float], list[float]]:
    """Process one batch of profiles through exactly 9 Qwen calls (8 slots + 1 answer).

    For each of the 8 sentence slots one prompt is built per profile:
      - profiles with LIME features in that slot → rewrite instruction
      - profiles without LIME features in that slot → "Return exactly the word: None"
    One model.generate() call serves the entire batch per slot.
    The answer rewrite follows the same pattern for the 9th call.

    Returns:
        failed     — profiles not approved (token budget or flip gate)
        n_approved — number of approved profiles in this batch
        cos_sims   — cosine similarities for approved profiles
        ppls       — perplexities for approved profiles
    """
    forbidden_phrases = FORBIDDEN_PHRASES_MAP[sub_dataset]
    n = len(batch)

    # Prepare per-profile CoT text and sentence-slot mapping
    for dp in batch:
        cot_text_only = dp["cot_text"].split("[ANSWER]")[0].strip()
        dp["_cot_text_only"] = cot_text_only
        # Per-sentence LIME: features are already assigned to (step, sent) slots
        slot_feature_map: dict[tuple[int, int], list[dict]] = lime_features[dp["id"]]
        sentence_map: dict[tuple[int, int], list[dict]] = {}
        all_top_k_words: list[str] = []
        for slot in _SENTENCE_SLOTS:
            feats = slot_feature_map.get(slot, [])
            if feats:
                filtered = _filter_positive_features(feats, top_k)
                if filtered:
                    sentence_map[slot] = filtered
                    all_top_k_words.extend(f["token"] for f in filtered)
        dp["_sentence_map"] = sentence_map
        dp["_top_k_words"] = list(dict.fromkeys(all_top_k_words))

    # 8 sentence-slot calls — exactly ONE generate() call per slot with N prompts
    modified_sentences: list[dict] = [{} for _ in batch]

    for slot in _SENTENCE_SLOTS:
        step_idx, sent_idx = slot
        messages_list: list[list[dict]] = []
        slot_sentences: list[str | None] = []

        for dp in batch:
            sentence_text: str | None = None
            if slot in dp["_sentence_map"]:
                steps = dp["_cot_text_only"].split("[EORS]")
                if step_idx < len(steps):
                    step_text = steps[step_idx].replace("[STEP]", "").strip()
                    sentences = step_text.split("[ES]")
                    if sent_idx < len(sentences):
                        s = sentences[sent_idx].strip()
                        if s:
                            sentence_text = s
            slot_sentences.append(sentence_text)

            if sentence_text is not None:
                current_lbl = id2label[dp["label"]]
                target_lbl = id2label[1 - dp["label"]]
                slot_feats = dp["_sentence_map"].get(slot, [])
                tokens_str = (
                    ", ".join(f["token"] for f in slot_feats)
                    if slot_feats
                    else "no specific signals identified"
                )
                messages_list.append(
                    [
                        {"role": "system", "content": sentence_system_prompt},
                        {
                            "role": "user",
                            "content": (
                                f"The following sentence currently supports '{current_lbl}' and must be rewritten to support '{target_lbl}'.\n\n"
                                f"#### Full Profile (for reference only) ####\n"
                                f"{dp['text']}\n\n"
                                f"#### Key word and number signals to target in this sentence ####\n"
                                f"{tokens_str}\n\n"
                                f"#### Sentence to Rewrite ####\n"
                                f"{sentence_text}\n"
                            ),
                        },
                    ]
                )
            else:
                messages_list.append(
                    [
                        {
                            "role": "user",
                            "content": "Return exactly the word: None",
                        }
                    ]
                )

        n_active = sum(1 for s in slot_sentences if s is not None)
        logger.info(f"Slot {slot}: {n_active}/{n} profiles active.")
        responses = _generate_qwen_batch(messages_list, qwen, qwen_tok, max_new_tokens)

        for i, (response, sentence_text) in enumerate(zip(responses, slot_sentences)):
            if sentence_text is None:
                continue
            # if response.strip().lower() == "none":
            #     continue
            rewritten = response.strip()
            contains_forbidden = any(
                re.search(pattern, rewritten, re.IGNORECASE)
                for pattern in forbidden_phrases
            )
            if contains_forbidden:
                logger.warning(
                    f"ID {batch[i]['id']} slot {slot}: rewritten sentence contains "
                    f"forbidden phrase, falling back to original."
                )
                modified_sentences[i][slot] = sentence_text
            else:
                # One-sentence check — fall back if Qwen returned multiple sentences
                sentences_returned = [
                    s.strip() for s in rewritten.split("\n") if s.strip()
                ]
                if len(sentences_returned) != 1:
                    logger.warning(
                        f"ID {batch[i]['id']} slot {slot}: Qwen returned multiple sentences, "
                        f"falling back to original."
                    )
                    modified_sentences[i][slot] = sentence_text
                else:
                    modified_sentences[i][slot] = rewritten
                    logger.debug(
                        f"ID {batch[i]['id']} slot {slot}: "
                        f"rewritten='{rewritten[:200]}...' original='{sentence_text[:200]}...'"
                    )

    # Reconstruct CoT steps + token budget check
    reconstructed: list[str | None] = []
    for i, dp in enumerate(batch):
        rec = _normalize_cot_spacing(
            _reconstruct_cot_steps(dp["_cot_text_only"], modified_sentences[i])
        )
        if not _check_token_budget(rec):
            logger.info(f"ID {dp['id']}: token budget exceeded, queuing for retry.")
            reconstructed.append(None)
        else:
            reconstructed.append(rec)

    # Answer rewrite — exactly ONE generate() call with N prompts
    passing_set = {i for i, r in enumerate(reconstructed) if r is not None}
    answer_messages: list[list[dict]] = []

    for i, dp in enumerate(batch):
        if i in passing_set:
            target_lbl = id2label[1 - dp["label"]]
            answer_messages.append(
                [
                    {"role": "system", "content": answer_system_prompt},
                    {
                        "role": "user",
                        "content": (
                            f"#### Modified Reasoning Steps ####\n"
                            f"{reconstructed[i]}\n\n"
                            f"Write an answer that reflects '{target_lbl}'."
                        ),
                    },
                ]
            )
        else:
            answer_messages.append(
                [
                    {
                        "role": "user",
                        "content": "Return exactly the word: None",
                    }
                ]
            )

    logger.info(f"Answer rewrite: {len(passing_set)}/{n} profiles passing.")
    all_answers = _generate_qwen_batch(answer_messages, qwen, qwen_tok, max_new_tokens)

    # Assemble CF CoT texts for passing profiles — kept as separate fields so
    # that flip gate and cosine similarity can operate on steps only while
    # perplexity can score the full sequence.
    counterfactual_cot_texts: dict[int, str] = {}  # steps only (up to final [EORS])
    counterfactual_answer_texts: dict[int, str] = {}  # answer block ([ANSWER]…[EOA])
    for i in passing_set:
        ans = all_answers[i].strip()
        if ans.lower() == "none":
            ans = ""
        counterfactual_cot_texts[i] = reconstructed[i]
        counterfactual_answer_texts[i] = ans

    # Flip gate + quality metrics
    gate_indices = list(counterfactual_cot_texts.keys())
    if gate_indices:
        # Validity and proximity are evaluated on cot_text only — student models
        # train on this field and the answer rewrite trivially contains the target
        # label, which would inflate flip-gate approval rates.
        cf_cot_only_texts = [counterfactual_cot_texts[i] for i in gate_indices]
        orig_labels = [batch[i]["label"] for i in gate_indices]
        flip_results = _check_label_flip_batch(
            cf_cot_only_texts, orig_labels, validator_pipe, validator_config.label_map
        )
        cos_sims = _compute_cosine_similarities(
            [batch[i]["cot_text"] for i in gate_indices], cf_cot_only_texts, sbert
        )
        # Perplexity measures fluency of the full output, including potential
        # stitching artifacts between the last reasoning step and the answer
        # block.  Validity and proximity are evaluated on cot_text only since
        # student models train on this field; fluency is evaluated on the full
        # output since it measures surface naturalness of the complete sequence.
        full_cf_texts = [
            counterfactual_cot_texts[i]
            + (
                "\n" + counterfactual_answer_texts[i]
                if counterfactual_answer_texts[i]
                else ""
            )
            for i in gate_indices
        ]
        ppls = _compute_perplexity(full_cf_texts, gpt2, gpt2_tok)
    else:
        cf_cot_only_texts = []
        flip_results = []
        cos_sims = []
        ppls = []

    approved_indices: set[int] = set()
    inv_label_map = {v: k for k, v in validator_config.label_map.items()}
    batch_cos_sims: list[float] = []
    batch_ppls: list[float] = []
    n_approved = 0

    for i, (flipped, pred, confidence), cos_sim, ppl in zip(
        gate_indices, flip_results, cos_sims, ppls
    ):
        dp = batch[i]
        target_int = 1 - dp["label"]
        orig_name = inv_label_map.get(dp["label"], str(dp["label"]))
        tgt_name = inv_label_map.get(target_int, str(target_int))
        if flipped:
            sorted_slots = sorted(modified_sentences[i].keys())
            record = {
                "id": f"cf_{dp['id']}",
                "original_id": dp["id"],
                "original_cot_text": dp["cot_text"],
                "original_answer_text": dp.get("answer_text", ""),
                "counterfactual_cot_text": counterfactual_cot_texts[i],
                "counterfactual_answer_text": counterfactual_answer_texts[i],
                "original_label": dp["label"],
                "counterfactual_label": target_int,
                "modified_sentences": [list(s) for s in sorted_slots],
                "top_k_words": dp["_top_k_words"],
                "cosine_similarity": round(float(cos_sim), 4),
                "ppl": round(float(ppl), 2),
                "target_label_confidence": round(float(confidence), 4),
                "retries": int(dp.get("_retry_count", 0)),
            }
            f_out.write(json.dumps(record, ensure_ascii=False) + "\n")
            f_out.flush()
            if on_approved is not None:
                on_approved(
                    dp["id"],
                    counterfactual_cot_texts[i],
                    counterfactual_answer_texts[i],
                )
            n_approved += 1
            approved_indices.add(i)
            batch_cos_sims.append(float(cos_sim))
            batch_ppls.append(float(ppl))
            logger.info(
                f"ID {dp['id']}: CF approved "
                f"(original={orig_name} → {tgt_name}, "
                f"pred_conf={confidence:.3f}, cos_sim={cos_sim:.3f}, ppl={ppl:.1f})"
            )
            cf_preview = counterfactual_cot_texts[i].replace("\n", " ")[:250]
            logger.info(f"  CF preview: {cf_preview}")
        else:
            pred_name = inv_label_map.get(pred, str(pred))
            logger.info(
                f"ID {dp['id']}: flip gate failed "
                f"(original={orig_name} → {tgt_name}, "
                f"pred={pred_name}, conf={confidence:.3f})"
            )

    failed = [batch[i] for i in range(n) if i not in approved_indices]
    return failed, n_approved, batch_cos_sims, batch_ppls


def run_cf_generation(
    config_path: str,
    split: str,
    top_k: int | None = None,
    pilot: bool = False,
    pilot_n: int = 100,
    extract_hidden_states: bool = False,
    teacher_model_suff: str | None = None,
) -> dict:
    """Generate counterfactuals for one split and return summary metrics.

    Per batch of batch_size profiles the pipeline makes exactly 9 Qwen calls:
    one per sentence slot (8 total) plus one answer rewrite.  Each call
    processes the full batch in a single model.generate() call, mirroring the
    ER-REASON preprocessing pipeline structure.

    Args:
        config_path:           Path to a counterfactual YAML config.
        split:                 "train", "val", or "test".
        top_k:                 Override the config's top_k (used by pilot experiment).
        pilot:                 If True, process only pilot_n profiles.
        pilot_n:               Number of profiles to process in pilot mode.
        extract_hidden_states: When True (and not pilot), run one forward pass per
                               approved profile with output_hidden_states=True and
                               save last-layer states at [EORS] / [EOA] positions
                               under data/hidden_states/{dataset}/cf/{split}/.
        teacher_model_suff:    Optional suffix appended to the teacher model name
                               before loading (e.g. "instruct" → "Qwen/Qwen3-4B-instruct").
                               If None the base model name from the config is used as-is.

    Returns:
        dict with keys: total_attempted, total_approved, slfr, avg_cosine_sim, avg_ppl, top_k
    """
    config = load_config(config_path)
    sub_dataset: str = config["dataset"]["sub_dataset"]
    split_cfg: dict = config["dataset"]["splits"][split]
    cot_input_path = resolve_path(split_cfg["cot_input"])
    lime_path = resolve_path(split_cfg["lime_output"])

    gen_cfg: dict = config["generation"]
    teacher_cfg: dict = gen_cfg["teacher_model"]
    model_name: str = teacher_cfg["name"]
    quantization: str | None = teacher_cfg.get("quantization")
    max_new_tokens: int = teacher_cfg.get("max_new_tokens", 512)
    batch_size: int = teacher_cfg.get("batch_size", 80)
    max_retries: int = gen_cfg.get("max_retries", 3)
    num_batches: int | None = gen_cfg.get("num_batches", None)
    id2label: dict[int, str] = {
        int(k): v for k, v in config["dataset"]["id2label"].items()
    }

    if top_k is None:
        top_k = gen_cfg.get("top_k", 5)

    if not teacher_model_suff or not split:
        print(
            "Please provide --teacher-model-suff, e.g. --teacher-model-suff Qwen3-8b --split test \nExiting."
        )
        sys.exit(1)

    _suff = f"_{teacher_model_suff}"
    if pilot:
        cf_output_base = split_cfg["cf_output"]
        cf_output_path = resolve_path(
            cf_output_base.replace(".jsonl", f"_pilot_k{top_k}{_suff}.jsonl")
        )
    else:
        cf_output_path = resolve_path(
            split_cfg["cf_output"].replace(".jsonl", f"{_suff}.jsonl")
        )

    cf_output_path.parent.mkdir(parents=True, exist_ok=True)
    validator_config = _SUB_DATASET_VALIDATOR[sub_dataset]

    # Load all four models once
    qwen, qwen_tok = _load_qwen(model_name, quantization)
    validator_pipe = _load_validator(validator_config.bert_model_path)
    sbert = _load_sbert()
    gpt2, gpt2_tok = _load_gpt2()

    # Build LIME feature lookup: profile_id → {(step, sent): [features]}
    lime_features: dict = {}
    with open(lime_path, "r") as f:
        for line in f:
            entry = json.loads(line.strip())
            slot_map: dict[tuple[int, int], list[dict]] = {}
            for sf in entry.get("sentence_features", []):
                slot_map[(sf["step"], sf["sentence"])] = sf["top_features"]
            lime_features[entry["id"]] = slot_map
    logger.info(f"Loaded LIME features for {len(lime_features)} profiles.")

    sentence_system_prompt = _load_prompt(sub_dataset, "sentence")
    answer_system_prompt = _load_prompt(sub_dataset, "answer")

    processed_ids = _load_processed_original_ids(cf_output_path)
    if processed_ids:
        logger.info(f"Resuming — {len(processed_ids)} profiles already processed.")

    # Build ordered list from CoT profiles
    all_data: list[dict] = []
    with open(cot_input_path, "r") as f_in:
        for line in f_in:
            dp = json.loads(line.strip())
            if dp["id"] in processed_ids:
                continue
            if dp["id"] not in lime_features:
                logger.warning(f"ID {dp['id']}: no LIME features, skipping.")
                continue
            if not any(feats for feats in lime_features[dp["id"]].values()):
                logger.warning(
                    f"ID {dp['id']}: all sentence LIME features empty, skipping."
                )
                continue
            all_data.append(dp)
            if pilot and len(all_data) >= pilot_n:
                break

    total_attempted = (
        min(len(all_data), num_batches * batch_size)
        if num_batches is not None
        else len(all_data)
    )
    total_approved = 0
    all_cos_sims: list[float] = []
    all_ppls: list[float] = []

    # ---- Hidden state extraction setup (skipped in pilot mode) ----
    on_approved = None
    if extract_hidden_states and not pilot:
        hs_subdir, hs_prefix = _CF_HS_DIR_MAP[sub_dataset]
        hs_split_dir = (
            PROJECT_ROOT / "data" / "hidden_states" / hs_subdir / "cf" / split
        )
        hs_temp_dir = (
            PROJECT_ROOT / "data" / "hidden_states" / hs_subdir / "cf" / "temp"
        )
        hs_split_dir.mkdir(parents=True, exist_ok=True)
        hs_temp_dir.mkdir(parents=True, exist_ok=True)

        _file_prefix = f"{hs_prefix}_cf_{split}{_suff}"
        cot_states_path = hs_split_dir / f"{_file_prefix}_cot_states.pt"
        answer_states_path = hs_split_dir / f"{_file_prefix}_answer_states.pt"
        index_path = hs_split_dir / f"{_file_prefix}_hidden_states_index.jsonl"

        hidden_dim: int = qwen.config.hidden_size

        # Count total CoT input profiles as a safe pre-allocation upper bound.
        n_cot_profiles = sum(1 for _ in open(cot_input_path, encoding="utf-8"))

        # Resumption: count index entries that reference the current split tensor.
        hs_next_row_idx = 0
        if index_path.exists():
            with open(index_path, encoding="utf-8") as _f:
                for _line in _f:
                    if json.loads(_line.strip()).get("cot_states_path") == str(
                        cot_states_path
                    ):
                        hs_next_row_idx += 1

        if cot_states_path.exists() and answer_states_path.exists():
            hs_cot_tensor = torch.load(cot_states_path, weights_only=True)
            hs_ans_tensor = torch.load(answer_states_path, weights_only=True)
            if hs_cot_tensor.shape != (n_cot_profiles, 4, hidden_dim):
                hs_cot_tensor = torch.zeros(n_cot_profiles, 4, hidden_dim)
                hs_ans_tensor = torch.zeros(n_cot_profiles, hidden_dim)
                hs_next_row_idx = 0
        else:
            hs_cot_tensor = torch.zeros(n_cot_profiles, 4, hidden_dim)
            hs_ans_tensor = torch.zeros(n_cot_profiles, hidden_dim)

        # Clean up stale temp files from a previous interrupted run.
        stale = list(hs_temp_dir.glob("*"))
        if stale:
            logger.info(f"CF HS: cleaning {len(stale)} stale temp file(s).")
            for _p in stale:
                _p.unlink()

        # All four BPE variants of each marker (bare / space-prefixed × trailing
        # newline or not) — mirrors the sequence set in _run_extraction_loop.
        eors_sequences = tuple(
            {
                tuple(qwen_tok.encode("[EORS]", add_special_tokens=False)),
                tuple(qwen_tok.encode(" [EORS]", add_special_tokens=False)),
                tuple(qwen_tok.encode("[EORS]\n", add_special_tokens=False)),
                tuple(qwen_tok.encode(" [EORS]\n", add_special_tokens=False)),
            }
        )
        eoa_sequences = tuple(
            {
                tuple(qwen_tok.encode("[EOA]", add_special_tokens=False)),
                tuple(qwen_tok.encode(" [EOA]", add_special_tokens=False)),
                tuple(qwen_tok.encode("[EOA]\n", add_special_tokens=False)),
                tuple(qwen_tok.encode(" [EOA]\n", add_special_tokens=False)),
            }
        )

        def _save_cf_hs_consolidated() -> None:
            torch.save(hs_cot_tensor, cot_states_path)
            torch.save(hs_ans_tensor, answer_states_path)

        def _cf_hs_callback(original_id: str, cot_text: str, answer_text: str) -> None:
            nonlocal hs_next_row_idx
            cot_states, answer_state, eors_pos, eoa_pos, err = (
                _extract_cf_profile_hidden_states(
                    original_id,
                    cot_text,
                    answer_text,
                    qwen,
                    qwen_tok,
                    eors_sequences,
                    eoa_sequences,
                    hidden_dim,
                    hs_temp_dir,
                )
            )
            if cot_states is None:
                logger.warning(f"CF HS: extraction failed for {original_id} — {err}")
                return
            pt_path, answer_pt_path, _ = promote_to_final(
                original_id, hs_temp_dir, hs_split_dir
            )
            hs_cot_tensor[hs_next_row_idx] = torch.load(pt_path, weights_only=True)
            hs_ans_tensor[hs_next_row_idx] = torch.load(
                answer_pt_path, weights_only=True
            )
            delete_per_profile_files(original_id, hs_split_dir)
            _save_cf_hs_consolidated()
            update_master_index(
                original_id,
                index_path,
                eors_pos,
                eoa_pos,
                cot_states_path,
                answer_states_path,
                hs_next_row_idx,
            )
            logger.info(
                f"CF HS: {original_id} → row {hs_next_row_idx} in consolidated tensors."
            )
            hs_next_row_idx += 1

        on_approved = _cf_hs_callback
        logger.info(
            f"CF hidden state extraction ENABLED — "
            f"output: {hs_split_dir}, resuming at row {hs_next_row_idx}."
        )

    logger.info("=" * 65)
    logger.info(f"CF generation  |  sub_dataset={sub_dataset}, split={split}")
    logger.info(f"  top_k         : {top_k}")
    logger.info(f"  batch_size    : {batch_size}")
    logger.info(f"  max_retries   : {max_retries}")
    logger.info(f"  total profiles: {total_attempted}")
    logger.info("=" * 65)

    with open(cf_output_path, "a") as f_out:
        all_failed: list[dict] = []

        for batch_idx, batch_start in enumerate(range(0, total_attempted, batch_size)):
            if num_batches is not None and batch_idx >= num_batches:
                logger.info(f"Reached num_batches={num_batches} limit, stopping.")
                break

            batch = all_data[batch_start : batch_start + batch_size]
            n = len(batch)
            logger.info(
                f"[{sub_dataset}] Batch {batch_idx + 1} — "
                f"profiles {batch_start + 1}–{batch_start + n} / {total_attempted}"
            )

            failed, n_approved, cos_sims, ppls = _process_batch(
                batch,
                f_out,
                qwen,
                qwen_tok,
                validator_pipe,
                sbert,
                gpt2,
                gpt2_tok,
                id2label,
                validator_config,
                lime_features,
                top_k,
                max_new_tokens,
                sentence_system_prompt,
                answer_system_prompt,
                sub_dataset,
                on_approved=on_approved,
            )
            total_approved += n_approved
            all_cos_sims.extend(cos_sims)
            all_ppls.extend(ppls)
            all_failed.extend(failed)
            logger.info(
                f"Batch {batch_idx + 1} main pass: "
                f"{n_approved} approved, {len(failed)} queued for retry."
            )

        # Global retry rounds — all failures collected before retrying
        retry_round = 0
        while all_failed and retry_round < max_retries:
            retry_round += 1
            logger.info(
                f"Global retry {retry_round}/{max_retries}: "
                f"{len(all_failed)} profile(s)"
            )
            for dp in all_failed:
                dp["_retry_count"] = dp.get("_retry_count", 0) + 1

            next_failed: list[dict] = []
            for batch_start in range(0, len(all_failed), batch_size):
                retry_batch = all_failed[batch_start : batch_start + batch_size]
                failed, n_approved, cos_sims, ppls = _process_batch(
                    retry_batch,
                    f_out,
                    qwen,
                    qwen_tok,
                    validator_pipe,
                    sbert,
                    gpt2,
                    gpt2_tok,
                    id2label,
                    validator_config,
                    lime_features,
                    top_k,
                    max_new_tokens,
                    sentence_system_prompt,
                    answer_system_prompt,
                    sub_dataset,
                    on_approved=on_approved,
                )
                total_approved += n_approved
                all_cos_sims.extend(cos_sims)
                all_ppls.extend(ppls)
                next_failed.extend(failed)

            logger.info(
                f"Global retry {retry_round} done — {len(next_failed)} still failing"
            )
            all_failed = next_failed

        if all_failed:
            logger.warning(
                f"{len(all_failed)} permanently failed after all retries. "
                f"IDs: {[dp['id'] for dp in all_failed]}"
            )

    slfr = total_approved / total_attempted if total_attempted > 0 else 0.0
    avg_cos = float(np.mean(all_cos_sims)) if all_cos_sims else 0.0
    avg_ppl = float(np.mean(all_ppls)) if all_ppls else 0.0

    summary = {
        "top_k": top_k,
        "total_attempted": total_attempted,
        "total_approved": total_approved,
        "slfr": round(slfr, 4),
        "avg_cosine_sim": round(avg_cos, 4),
        "avg_ppl": round(avg_ppl, 2),
    }
    logger.info(
        f"\nDone! top_k={top_k} | SLFR={slfr:.2%} | "
        f"avg_cos={avg_cos:.3f} | avg_ppl={avg_ppl:.1f} | "
        f"output: {cf_output_path}"
    )
    return summary
